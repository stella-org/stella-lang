// Writes `compiler/src/Stella/Compiler/Bootstrap/Source.purs`: the interface and
// the bytecode of each module the compiler carries, compiled from its source,
// so the compiler holds those modules without reading a file or compiling
// anything as it starts.
//
// The sources are built together, by one toolchain build compiling all of them
// anew, so what is written is a function of the sources and of the compiler
// that builds them, and of no module the compiler carried before. The build is
// `stellac build`'s development entry point, which needs the workspace built.
//
// Run from the repository root or from `compiler/`: `npm run embed -w compiler`.

import { spawnSync } from "node:child_process";
import { mkdtempSync, mkdirSync, readFileSync, rmSync, copyFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const output = "compiler/src/Stella/Compiler/Bootstrap/Source.purs";

// Each module the compiler carries, in the order a build compiles them: the
// value the generated module holds it as, and its source, relative to the root
// and to the source directory of its package.
const sources = [
  { value: "baseInt", module: "Base.Int", package: "stella-packages/base", path: "Base/Int.stel" },
  { value: "stellaSyntax", module: "Stella.Syntax", package: "stella-packages/compiler-lib", path: "Stella/Syntax.stel" },
  { value: "stellaElab", module: "Stella.Elab", package: "stella-packages/compiler-lib", path: "Stella/Elab.stel" },
];

const work = mkdtempSync(join(tmpdir(), "stella-embed-"));
try {
  for (const s of sources) {
    const to = join(work, "src", s.path);
    mkdirSync(dirname(to), { recursive: true });
    copyFileSync(join(root, s.package, "src", s.path), to);
  }
  const rebuilt = sources.flatMap((s) => ["--toolchain-rebuild", s.module]);
  const built = spawnSync("node", [join(root, "stellac/index.dev.js"), "build", "--workdir", work, ...rebuilt], {
    stdio: ["ignore", "ignore", "inherit"],
  });
  if (built.status !== 0) {
    throw new Error("the modules the compiler carries did not build; is the workspace built?");
  }

  const hex = (path) => readFileSync(path).toString("hex");
  const artifact = (s, ext) => hex(join(work, "output", "_build", `${s.module}.${ext}`));

  const header = [
    "-- | The modules the compiler carries, as the files a build of their sources",
    "-- | writes: each module's interface and bytecode, in hexadecimal.",
    "-- |",
    "-- | **Generated by `npm run embed -w compiler`; do not edit.** The sources are",
    "-- | the modules' source of truth, compiled together by one toolchain build:",
    "-- |",
    ...sources.map((s) => `-- | - \`${s.package}/src/${s.path}\``),
  ];

  const values = sources.flatMap((s) => [
    "",
    `-- | \`${s.module}\`, from \`${s.package}/src/${s.path}\`.`,
    `${s.value} :: Carried`,
    `${s.value} =`,
    `  { interface: "${artifact(s, "dmi")}"`,
    `  , bytecode: "${artifact(s, "dmo")}"`,
    "  }",
  ]);

  const text = [
    ...header,
    `module Stella.Compiler.Bootstrap.Source (Carried, ${sources.map((s) => s.value).join(", ")}) where`,
    "",
    "-- | A module's interface file and bytecode file, each in hexadecimal.",
    "type Carried = { interface :: String, bytecode :: String }",
    ...values,
    "",
  ].join("\n");

  writeFileSync(join(root, output), text);
} finally {
  rmSync(work, { recursive: true, force: true });
}
