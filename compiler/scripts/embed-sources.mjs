// Writes `compiler/src/Stella/Compiler/Bootstrap/Source.purs`: the text of each
// source the compiler carries, as a string, so the compiler builds those modules
// without reading a file. The output is a function of the sources alone.
//
// Run from the repository root or from `compiler/`: `npm run embed -w compiler`.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const output = "compiler/src/Stella/Compiler/Bootstrap/Source.purs";

// Each value the module exports, and the source it holds, relative to the root.
const sources = [{ value: "baseInt", path: "stella-packages/base/src/Base/Int.stel" }];

// A PureScript string literal of the text: the quote, the backslash, and the
// line breaks escaped, and any other control character refused.
const literal = (path, text) =>
  '"' +
  Array.from(text, (c) => {
    if (c === '"') return '\\"';
    if (c === "\\") return "\\\\";
    if (c === "\n") return "\\n";
    if (c === "\r") return "\\r";
    const code = c.codePointAt(0);
    if (code < 0x20 || code === 0x7f) throw new Error(`${path}: control character U+${code.toString(16).padStart(4, "0")}`);
    return c;
  }).join("") +
  '"';

const header = [
  "-- | The sources of the modules the compiler carries, as text.",
  "-- |",
  "-- | **Generated by `npm run embed -w compiler`; do not edit.** Each value is",
  "-- | the text of the file it names, and the file is the module's source of",
  "-- | truth:",
  "-- |",
  ...sources.map(({ path }) => `-- | - \`${path}\``),
];

const values = sources.flatMap(({ value, path }) => [
  "",
  `-- | The text of \`${path}\`.`,
  `${value} :: String`,
  `${value} = ${literal(path, readFileSync(join(root, path), "utf8"))}`,
]);

const text = [
  ...header,
  `module Stella.Compiler.Bootstrap.Source (${sources.map((s) => s.value).join(", ")}) where`,
  ...values,
  "",
].join("\n");

writeFileSync(join(root, output), text);
