// Writes `compiler/src/Stella/Compiler/Bootstrap/Source.purs`: the interface and
// the bytecode of each seed module compiled from its source, so the compiler
// holds the seed modules without reading a file or compiling anything as it
// starts.
//
// The files are what `stella-devtools build-seeds` writes in one seed build
// that compiles every source anew, so they depend only on the sources and the
// compiler building them, never on the seed modules it held before. The build
// writes to a directory of its own, and the compiler's file is written only
// once it succeeds. It runs from the workspace's build output, which needs
// the workspace built.
//
// Run from the repository root or from `compiler/`: `npm run embed -w compiler`.

import { spawnSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const output = "compiler/src/Stella/Compiler/Bootstrap/Source.purs";

// Each seed module, in the order a build compiles them: the
// value the generated module holds it as, and its source, relative to the root
// and to the source directory of its package.
const sources = [
  { value: "baseInt", module: "Base.Int", package: "stella-packages/base", path: "Base/Int.stel" },
  { value: "stellaSyntax", module: "Stella.Syntax", package: "stella-packages/compiler-lib", path: "Stella/Syntax.stel" },
  { value: "stellaElab", module: "Stella.Elab", package: "stella-packages/compiler-lib", path: "Stella/Elab.stel" },
];

const work = mkdtempSync(join(tmpdir(), "stella-embed-"));
try {
  const built = spawnSync("node", [join(root, "devtools/index.js"), "build-seeds", "--output", work], {
    cwd: root,
    stdio: ["ignore", "ignore", "inherit"],
  });
  if (built.status !== 0) {
    throw new Error("the seed modules did not build; is the workspace built?");
  }

  const hex = (path) => readFileSync(path).toString("hex");
  const artifact = (s, ext) => hex(join(work, `${s.module}.${ext}`));

  const header = [
    "-- | The seed modules, which are loaded as the compiler bootstraps, as the",
    "-- | files a build of their sources writes: each module's interface and",
    "-- | bytecode, in hexadecimal.",
    "-- |",
    "-- | **Generated by `npm run embed -w compiler`; do not edit.** The sources are",
    "-- | the modules' source of truth, compiled together by one seed build:",
    "-- |",
    ...sources.map((s) => `-- | - \`${s.package}/src/${s.path}\``),
  ];

  const values = sources.flatMap((s) => [
    "",
    `-- | \`${s.module}\`, from \`${s.package}/src/${s.path}\`.`,
    `${s.value} :: Carried`,
    `${s.value} =`,
    `  { interface: "${artifact(s, "dmi")}"`,
    `  , bytecode: "${artifact(s, "dmo")}"`,
    "  }",
  ]);

  const text = [
    ...header,
    `module Stella.Compiler.Bootstrap.Source (Carried, ${sources.map((s) => s.value).join(", ")}) where`,
    "",
    "-- | A module's interface file and bytecode file, each in hexadecimal.",
    "type Carried = { interface :: String, bytecode :: String }",
    ...values,
    "",
  ].join("\n");

  writeFileSync(join(root, output), text);
} finally {
  rmSync(work, { recursive: true, force: true });
}
